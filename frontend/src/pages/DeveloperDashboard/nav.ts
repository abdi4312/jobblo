export const DEV_NAV_ITEMS = DEV_NAV.flatMap((g) => g.items);
export const findNavItem = (path: string) => DEV_NAV_ITEMS.find((i) => i.path === path);
/** The nav item a URL belongs to: the longest item path that is the URL or a parent of it ("redis/keys" over "redis"). */
export const activeNavPath = (pathname: string) => {
  const rest = pathname.replace(/^\/developer\/?/, '').replace(/\/$/, '');
  return DEV_NAV_ITEMS.map((i) => i.path).filter((p) => p === rest || (p && rest.startsWith(`${p}/`))).sort((a, b) => b.length - a.length)[0];
};

